const fs = require('fs/promises');
const path = require('path');
const crypto = require('crypto');

const { customQuery } = require('./dbFunctions');

// Where uploaded files live (same approach as Pharmalyx). Callers only use put / get / remove with a storage key.
//   FILE_STORE=db : in the database (dbo.FileBlobs), for hosts without a lasting disk.
//   otherwise     : a folder on the server (UPLOAD_DIR, default ./uploads).
// Both APIs must use the same store so the shop can show photos the owner uploads.
const ROOT = path.resolve(process.env.UPLOAD_DIR || path.join(__dirname, '..', 'uploads'));
const USE_DB = String(process.env.FILE_STORE || '').toLowerCase() === 'db';

// Keys are generated by the server ("products/<productId>/<uuid>.jpg"); never trust a client path.
const resolveKey = (key) => {
    const full = path.resolve(ROOT, key);
    if (!full.startsWith(ROOT + path.sep)) throw new Error('Invalid storage key.');
    return full;
};

const put = async (key, buffer) => {
    resolveKey(key);
    if (USE_DB) {
        await customQuery(
            `UPDATE dbo.FileBlobs SET Data = @Data, SizeBytes = @SizeBytes, CreatedOn = SYSUTCDATETIME() WHERE StorageKey = @Key;
             IF @@ROWCOUNT = 0 INSERT INTO dbo.FileBlobs (StorageKey, Data, SizeBytes, CreatedOn) VALUES (@Key, @Data, @SizeBytes, SYSUTCDATETIME());`,
            { Key: key, Data: buffer, SizeBytes: buffer.length }
        );
        return key;
    }
    const full = resolveKey(key);
    await fs.mkdir(path.dirname(full), { recursive: true });
    await fs.writeFile(full, buffer);
    return key;
};

const get = async (key) => {
    const full = resolveKey(key);
    if (USE_DB) {
        const [row] = await customQuery('SELECT Data FROM dbo.FileBlobs WHERE StorageKey = @Key', { Key: key });
        if (row?.Data) return Buffer.from(row.Data);
    }
    return fs.readFile(full);
};

const remove = async (key) => {
    const full = resolveKey(key);
    if (USE_DB) await customQuery('DELETE FROM dbo.FileBlobs WHERE StorageKey = @Key', { Key: key });
    await fs.unlink(full).catch((error) => {
        if (error.code !== 'ENOENT') throw error;
    });
};

// Recognises file types from their first bytes, not from what the client claims.
const sniff = (buffer) => {
    if (!buffer || buffer.length < 12) return null;
    if (buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff) return { contentType: 'image/jpeg', ext: 'jpg' };
    if (buffer.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return { contentType: 'image/png', ext: 'png' };
    if (buffer.subarray(0, 4).toString('ascii') === 'RIFF' && buffer.subarray(8, 12).toString('ascii') === 'WEBP') return { contentType: 'image/webp', ext: 'webp' };
    if (buffer.subarray(0, 5).toString('ascii') === '%PDF-') return { contentType: 'application/pdf', ext: 'pdf' };
    return null;
};

// "data:image/png;base64,...." → { buffer, type } after checking the real type and the size.
const fromDataUrl = (dataUrl, { allow, maxBytes }) => {
    const match = /^data:[\w/+.-]+;base64,([A-Za-z0-9+/=]+)$/.exec(String(dataUrl || ''));
    if (!match) return null;
    const buffer = Buffer.from(match[1], 'base64');
    const type = sniff(buffer);
    if (!type || !allow.includes(type.contentType) || buffer.length > maxBytes) return null;
    return { buffer, type };
};

const newKey = (folder, ext) => `${folder}/${crypto.randomUUID()}.${ext}`;

const CONTENT_TYPES = { jpg: 'image/jpeg', png: 'image/png', webp: 'image/webp', pdf: 'application/pdf' };
const contentTypeOf = (key) => CONTENT_TYPES[String(key).split('.').pop().toLowerCase()] || 'application/octet-stream';

// Sends a stored file (404 when missing). Cached a day: keys never change once written.
const sendFile = async (res, key) => {
    try {
        const data = await get(key);
        res.set('Content-Type', contentTypeOf(key));
        res.set('Cache-Control', 'public, max-age=86400, immutable');
        res.send(data);
    } catch {
        res.status(404).json({ message: 'File not found.' });
    }
};

module.exports = { put, get, remove, sniff, fromDataUrl, newKey, contentTypeOf, sendFile };
